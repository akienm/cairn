NOW = datetime(2026, 11, 13, 12, 0, tzinfo=timezone.utc)
_REFUSAL = "testing-9dbac8691def the harbor refused this boat"
_SCRATCH = contextlib.ExitStack()


def _stub_codemother():
    from cairn.tools.base.device import BaseDevice

    class StubCodemother(BaseDevice):
        """Answers 'sealed' the way codemother's shim does: crossed[] and refused[]."""

        def intention(self) -> dict:
            return {"what": "testing-9dbac8691def stub codemother"}

        def state(self) -> dict:
            return {"at": "running"}

        def settings(self) -> dict:
            return {}

        def declared_verbs(self) -> dict:
            return {"sealed": lambda envelope: {
                "accepted": True, "verb": "sealed",
                "crossed": ["testing-crossed-9dba"],
                "refused": [{"ticket": "testing-refused-9dba", "reason": _REFUSAL}],
                "awaiting_hollow": []}}

    return StubCodemother()


def _far_rig():
    """A scratch bus with codemother held and the tester held NOWHERE — a far home's view."""
    from cairn.tools.base.shim import BaseShim, ONLINE
    from cairn.devices.cairn.tools.scratch_bus.scratch_bus import scratch_bus, bus_shim
    from cairn.tools.bus_client.roster import DeviceRoster

    class _Shim(BaseShim):
        def __init__(self, device_id, device, bus) -> None:
            super().__init__(bus=bus)
            self._device_id = device_id
            self._device = device
            self._presence = ONLINE

        @property
        def device_id(self) -> str:
            return self._device_id

        def _start_device(self):
            return self._device

    bus = _SCRATCH.enter_context(scratch_bus("bus_fsr"))
    loop = DeviceRoster(bus)
    loop.hold(bus_shim(bus, loop))
    loop.hold(_Shim("codemother", _stub_codemother(), bus))
    loop.pulse(NOW)
    return bus


@contextlib.contextmanager
def _as_a_far_home(bus):
    import cairn.tools.bus_client as bc
    from cairn.tools.bus_client import remote
    was_reach, was_addr = bc.reach, remote.remote_address
    bc.reach = lambda *devices: bus
    remote.remote_address = lambda home=None: ("testing-far-home.local", 7419)
    try:
        yield
    finally:
        bc.reach, remote.remote_address = was_reach, was_addr


def _announce(bus, n=1):
    from cairn.devices.tester import cli
    from cairn.devices.tester.device import TesterDevice
    proof = _REPO_ROOT / "cairn/devices/tester/proofs/test_a_far_seal_run_takes_its_own_replies.py"
    sealed = [(proof, {"verdict": "green", "evidence": {"source_fingerprint": "testing"}})] * n
    out = io.StringIO()
    with _as_a_far_home(bus), contextlib.redirect_stdout(out):
        cli._announce_seals(TesterDevice(), sealed)
    return out.getvalue()


def test_a_far_seal_run_leaves_no_reply_standing():
    from cairn.devices.db_domain.tools.client import store
    bus = _far_rig()
    printed = _announce(bus)
    replies = bus.read(to="tester", channel="personal")
    assert replies, f"the stub codemother never replied — no exchange happened: {printed!r}"
    left = bus.undelivered(to="tester", limit=1000)
    assert not left, f"{len(left)} sealed reply(ies) stand undelivered to the tester: {left}"
    rows = store.read(bus.delivery_table, where="envelope = %s", params=(replies[0]["id"],))
    assert rows and all(r.get("by") == "tester" for r in rows), (
        f"the reply's receipt is not the tester's own: {rows}")


def test_the_refused_line_is_printed_at_a_far_exchange():
    bus = _far_rig()
    printed = _announce(bus)
    print("       " + printed.replace("\n", "\n       ").rstrip())
    assert "refused: testing-refused-9dba" in printed and _REFUSAL in printed, (
        f"the refused seal was not printed at the far exchange; stdout was {printed!r}")


def test_standing_replies_are_taken_and_a_request_stays():
    bus = _far_rig()
    earlier = bus.post(sender="codemother", to="tester", channel="personal", verb="sealed reply",
                       why="testing-9dbac8691def an earlier run's reply",
                       body={"crossed": [], "refused": []}, reply_to="testing-earlier-post")
    request = bus.post(sender="testing-9dbac8691def", to="tester", channel="personal",
                       verb="testing-not-a-reply", why="testing-9dbac8691def a request",
                       body={})
    bus.flush()
    _announce(bus)
    left = {env["id"] for env in bus.undelivered(to="tester", limit=1000)}
    assert earlier["id"] not in left, "a reply standing from an earlier run was not taken"
    assert request["id"] in left, "a non-reply envelope to the tester was taken; only replies are"


