"""PROOF for ticket 9dbac8691def: a far seal run takes its own sealed replies.

Measured 2026-11-13 on akienasus: CAIRN_BUS_HOME=akiendelllinux.local:7419, so ``reach``
holds nothing (a far home holds nothing, ticket bc0bbfd33a71) and the tester's shim is wired
nowhere. Codemother answers each seal with a "sealed reply" to the tester, and every one stood
undelivered on the Dell's bus: 64 after one 59-proof reseal. Akien, open-9d1bb9b4d708: "All
mail generated by tester has to be managed by the testers shim. Period."

The far home is simulated over a scratch bus: ``cairn.tools.bus_client.reach`` is patched to
hand back a scratch bus where ONLY a stub codemother is held (the tester wired nowhere, as on
a far home), and ``remote.remote_address`` to answer a far address. Both are restored after.
The REAL ``cli._announce_seals`` runs, bound at call time.

  1. with codemother wired, the tester wired nowhere and the home far, _announce_seals
     leaves undelivered(to='tester') empty and the reply's receipt is by tester.
  2. the reply's refused line is printed at the exchange.
  3. sealed replies standing before the run are taken too, and a non-reply envelope to
     tester stays undelivered.

Requires Postgres; every bus rides scratch_bus and drops at close.

    bin/cairn test <this file>
"""

